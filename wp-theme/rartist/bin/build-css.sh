#!/usr/bin/env bash
#
# Concatenate the stylesheet manifest into assets/css/main.css.
#
# Optional: the theme enqueues the individual parts when main.css is absent or when
# WP_DEBUG is on, so development never needs this. Run it before deploying to serve
# one file instead of fifteen.
#
# Usage: bin/build-css.sh
#
set -euo pipefail

theme_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out="$theme_dir/assets/css/main.css"

# The order comes from the manifest in inc/assets.php — one list, never two.
# Written as a read loop rather than mapfile: macOS still ships bash 3.2.
files=()
while IFS= read -r line; do
	files+=("$line")
done < <(sed -n "s/^[[:space:]]*'\(assets\/css\/[^']*\)',$/\1/p" "$theme_dir/inc/assets.php")

if [ "${#files[@]}" -eq 0 ]; then
	echo "No stylesheets found in inc/assets.php manifest." >&2
	exit 1
fi

{
	echo "/* Rartist Studio — generated by bin/build-css.sh. Do not edit. */"
	for file in "${files[@]}"; do
		echo ""
		echo "/* ---- $file ---- */"
		cat "$theme_dir/$file"
	done
} > "$out"

echo "Wrote $(basename "$out") from ${#files[@]} files ($(wc -c < "$out" | tr -d ' ') bytes)"
